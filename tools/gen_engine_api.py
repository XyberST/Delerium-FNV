"""Regenerates src/engine_api.inc from delirium_physics.h (run after updating the engine SDK)."""
import re, sys
hdr = open(sys.argv[1]).read()
out = ['// generated by tools/gen_engine_api.py - do not edit']
for m in re.finditer(r'^NM_API\s+(.+?)\s+(\**)(nm_\w+)\((.*?)\);', hdr, re.M):
    ret, stars, name, args = m.groups()
    out.append('NM_FN(%s, %s, (%s))' % (ret + (' ' + stars if stars else ''), name, args))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(out) - 1, 'functions')
